    capsule(d,ank,heel,11,9,SK);capsule(d,heel,B,11,9,SK);capsule(d,B,(B[0]+14,B[1]+1),10,8,SK)
    padc=(knee[0]-4,knee[1]-24)
    rect(d,padc[0]-24,padc[1]-8,padc[0]+22,padc[1]+8,(60,70,90,255),6)
